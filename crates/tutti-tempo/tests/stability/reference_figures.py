"""Writes figures.rs: tempo-ramp figures from 80-digit decimal arithmetic.

Independent of the crate: the formulas are the definitions (rates r = bpm / 60,
db beats from r0 to r1), evaluated with Python's `decimal`, which shares no
code with `libm` or the Rust map.

* time ramp:  T = 2 db / (r0 + r1), a = (r1 - r0) / T,
              beats(s) = r0 s + a s^2 / 2,  s(b) = 2 b / (r0 + sqrt(r0^2 + 2 a b))
* beat ramp:  g = (r1 - r0) / db,
              s(b) = ln(1 + g b / r0) / g,  beats(s) = r0 (exp(g s) - 1) / g

Each row is (beat in, seconds out, seconds in, beat out): the Rust test feeds
the first to `seconds_at` and the third to `beat_at_seconds`. The inputs are
the f64 values the test passes, taken exactly, so no row carries input rounding.

Run: python3 -I reference_figures.py > figures.rs && rustfmt figures.rs  (from this directory)
"""
from decimal import Decimal as D, getcontext

getcontext().prec = 80

NEAR = 120.0000001
CASES = [
    ("near_equal_1e-7", 120.0, NEAR, 4.0),
    ("near_equal_2_pow_minus_45", 120.0, 120.0 + 2.0**-45, 4.0),
    ("near_equal_one_ulp", 120.0, 120.0 + 2.0**-46, 4.0),
    ("steep_up", 20.0, 999.0, 8.0),
    ("steep_down", 999.0, 20.0, 8.0),
    ("very_short_span", 20.0, 999.0, 1e-9),
    ("very_long_steep", 20.0, 999.0, 1e6),
    ("very_long_near_equal", 120.0, NEAR, 1e6),
]
FRACS = ["0", "1e-6", "0.25", "0.5", "0.999999", "1"]


def seconds(shape, r0, r1, db, b):
    if shape == "time":
        t = 2 * db / (r0 + r1)
        a = (r1 - r0) / t
        return 2 * b / (r0 + (r0 * r0 + 2 * a * b).sqrt())
    g = (r1 - r0) / db
    return (1 + g * b / r0).ln() / g


def beats(shape, r0, r1, db, s):
    if shape == "time":
        t = 2 * db / (r0 + r1)
        a = (r1 - r0) / t
        return r0 * s + a * s * s / 2
    g = (r1 - r0) / db
    return r0 * ((g * s).exp() - 1) / g


print("// Generated by reference_figures.py; do not edit.")
print("use super::Case;")
print("pub(super) const CASES: &[Case] = &[")
for shape in ("time", "beats"):
    for name, b0, b1, db in CASES:
        r0, r1, dbd = D(b0) / 60, D(b1) / 60, D(db)
        rows = []
        for fr in FRACS:
            bin_ = float(dbd * D(fr))
            sec_out = seconds(shape, r0, r1, dbd, D(bin_))
            sec_in = float(sec_out)
            beat_out = beats(shape, r0, r1, dbd, D(sec_in))
            rows.append((bin_, float(sec_out), sec_in, float(beat_out)))
        print(f'    Case {{ name: "{name}", ramp_beats: {str(shape == "beats").lower()}, from: {b0!r}, to: {b1!r}, span: {db!r}, rows: &[')
        for r in rows:
            print("        (" + ", ".join(repr(x) for x in r) + "),")
        print("    ] },")
print("];")
