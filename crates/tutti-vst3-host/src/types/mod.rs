/// A parameter's own `[min, max]`, as the plugin's controller maps the
/// normalized endpoints. `min <= max`; a constant parameter has `min == max`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PlainRange {
    /// The plain value at normalized 0 or 1, whichever is lower.
    pub min: f64,
    /// The plain value at normalized 0 or 1, whichever is higher.
    pub max: f64,
}

/// The modifier keys held during a key event (`KeyModifier`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct KeyModifiers(i16);

impl KeyModifiers {
    /// No modifier.
    pub const NONE: Self = Self(0);
    /// Shift.
    pub const SHIFT: Self = Self(sdk_enum_i32(Key::kShiftKey) as i16);
    /// Alt on Windows, Option on macOS.
    pub const ALTERNATE: Self = Self(sdk_enum_i32(Key::kAlternateKey) as i16);
    /// Command on macOS, Control on Windows and Linux.
    pub const COMMAND: Self = Self(sdk_enum_i32(Key::kCommandKey) as i16);
    /// Control on macOS, Windows key on Windows.
    pub const CONTROL: Self = Self(sdk_enum_i32(Key::kControlKey) as i16);

    /// The `KeyModifier` bitmask.
    #[must_use]
    pub const fn bits(self) -> i16 {
        self.0
    }

    /// Whether every modifier in `other` is held.
    #[must_use]
    pub const fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }
}

impl std::ops::BitOr for KeyModifiers {
    type Output = Self;

    fn bitor(self, rhs: Self) -> Self {
        Self(self.0 | rhs.0)
    }
}

/// One key event offered to a plugin's editor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeyEvent {
    /// The UTF-16 unit typed, or `0` for a key with no character.
    pub character: u16,
    /// The SDK's `VirtualKeyCode`, or `0` for a plain character key.
    pub virtual_key: i16,
    /// The modifiers held.
    pub modifiers: KeyModifiers,
}

impl KeyEvent {
    /// A character key with no modifier.
    #[must_use]
    pub const fn character(character: u16) -> Self {
        Self {
            character,
            virtual_key: 0,
            modifiers: KeyModifiers::NONE,
        }
    }

    /// A non-character key, by the SDK's virtual key code, with no modifier.
    #[must_use]
    pub const fn virtual_key(virtual_key: i16) -> Self {
        Self {
            character: 0,
            virtual_key,
            modifiers: KeyModifiers::NONE,
        }
    }
}

/// What an editor did with an offered key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyOutcome {
    /// The editor took the key; the host must not act on it.
    Consumed,
    /// The editor ignored the key, or no editor is open.
    Ignored,
}

impl KeyOutcome {
    /// Whether the editor took the key.
    #[must_use]
    pub fn is_consumed(self) -> bool {
        self == Self::Consumed
    }
}

/// Events and parameter changes emitted by the plugin during one call to
/// [`Vst3Processor::process`](crate::Vst3Processor::process).
///
/// Owned variant. Off-RT callers (tests, offline render) can keep this
/// around. RT callers should use [`ProcessOutputRef`] instead — it
/// borrows the instance's pooled buffers without copying.
#[derive(Debug)]
pub struct ProcessOutput {
    /// MIDI events generated by the plugin (e.g. arpeggiator output).
    pub midi_events: Vec<WireMidi>,
    /// Parameter changes reported via `outputParameterChanges` — typically
    /// used by plugins with host-visible automation readouts.
    pub parameter_changes: ParameterChanges,
}

/// Borrowing view of the plugin's per-block output. Points into the
/// `Vst3Processor`'s pooled return-value buffers — valid until the next
/// `process` call, which clears them in place. RT-safe.
#[derive(Debug, Clone, Copy)]
pub struct ProcessOutputRef<'a> {
    /// MIDI the plugin emitted this block, in the pooled buffer.
    pub midi_events: &'a [WireMidi],
    /// Parameter changes the plugin reported via `outputParameterChanges`.
    pub parameter_changes: &'a ParameterChanges,
}

impl<'a> ProcessOutputRef<'a> {
    /// Snapshots into an owned [`ProcessOutput`]. Allocates; off-RT only.
    #[must_use]
    pub fn to_owned(self) -> ProcessOutput {
        ProcessOutput {
            midi_events: self.midi_events.to_vec(),
            parameter_changes: self.parameter_changes.clone(),
        }
    }
}

/// Identity + capability descriptor for a plugin class.
///
/// Populated by [`Vst3Loaded::probe`](crate::Vst3Loaded::probe) /
/// [`Vst3Loaded::load`](crate::Vst3Loaded::load); builder methods on this
/// type are exposed so hosts that wrap multiple plugin formats can
/// construct equivalent `PluginInfo` values by hand.
#[derive(Debug, Clone)]
pub struct PluginInfo {
    /// Unique id, formatted as `vst3.<CID>` by this crate.
    pub id: String,
    /// Display name from the factory's class info.
    pub name: String,
    /// Vendor string; empty when the factory declares none.
    pub vendor: String,
    /// Vendor-formatted version string; empty when the factory declares none.
    pub version: String,
    /// Input channel count on bus 0.
    pub num_inputs: usize,
    /// Output channel count on bus 0.
    pub num_outputs: usize,
    /// Per-bus channel counts for every audio **input** bus, in bus-index
    /// order. `input_bus_channels[0]` mirrors [`num_inputs`](Self::num_inputs)
    /// (the main bus); subsequent entries are aux/sidechain input buses.
    /// Empty when the plugin has no audio input buses.
    pub input_bus_channels: Vec<usize>,
    /// Per-bus channel counts for every audio **output** bus, in bus-index
    /// order. `output_bus_channels[0]` mirrors
    /// [`num_outputs`](Self::num_outputs) (the main bus); subsequent entries
    /// are aux output buses. Empty when the plugin has no audio output buses.
    pub output_bus_channels: Vec<usize>,
    /// `true` if the plugin exposes at least one input event bus.
    pub has_midi_input: bool,
    /// `true` if the plugin exposes at least one output event bus (emits MIDI
    /// the host can read back).
    pub has_midi_output: bool,
    /// `true` if the plugin advertises `kSample64` processing.
    pub supports_f64: bool,
    /// The plugin's declared subcategories, `|`-delimited (`"Fx|Reverb"`,
    /// `"Instrument|Synth"`), from `PClassInfoW::subCategories`.
    ///
    /// `None` when the factory implements only `IPluginFactory`, whose class
    /// struct has no such field — distinct from `Some("")`, which would mean a
    /// factory that can report them and declared none.
    pub sub_categories: Option<String>,
}

impl PluginInfo {
    /// Starts a descriptor from the two fields with no sensible default.
    /// Channel counts default to stereo in and out; every other field is empty
    /// or `false` until a builder method sets it.
    pub fn new(id: impl Into<String>, name: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            name: name.into(),
            vendor: String::new(),
            version: String::new(),
            num_inputs: 2,
            num_outputs: 2,
            input_bus_channels: Vec::new(),
            output_bus_channels: Vec::new(),
            has_midi_input: false,
            has_midi_output: false,
            supports_f64: false,
            sub_categories: None,
        }
    }

    /// Sets the vendor string.
    #[must_use]
    pub fn vendor(mut self, vendor: impl Into<String>) -> Self {
        self.vendor = vendor.into();
        self
    }

    /// Sets the version string.
    #[must_use]
    pub fn version(mut self, version: impl Into<String>) -> Self {
        self.version = version.into();
        self
    }

    /// Sets the `|`-delimited subcategories. Takes an `Option` rather than a
    /// string so a v1-only factory's "cannot report" survives the builder — see
    /// [`sub_categories`](Self::sub_categories).
    #[must_use]
    pub fn sub_categories(mut self, sub_categories: Option<String>) -> Self {
        self.sub_categories = sub_categories;
        self
    }

    /// Sets the bus-0 channel counts. For plugins with aux or sidechain buses,
    /// follow with [`bus_channels`](Self::bus_channels) — the totals fall back
    /// to these counts only while no per-bus layout is recorded.
    #[must_use]
    pub fn audio_io(mut self, inputs: usize, outputs: usize) -> Self {
        self.num_inputs = inputs;
        self.num_outputs = outputs;
        self
    }

    /// Records the full per-bus channel layout (one entry per audio bus, in
    /// bus-index order). The main bus (`[0]`) is expected to match
    /// [`num_inputs`](Self::num_inputs) / [`num_outputs`](Self::num_outputs).
    #[must_use]
    pub fn bus_channels(
        mut self,
        input_bus_channels: Vec<usize>,
        output_bus_channels: Vec<usize>,
    ) -> Self {
        self.input_bus_channels = input_bus_channels;
        self.output_bus_channels = output_bus_channels;
        self
    }

    /// Total input channels across all audio input buses (main + aux). Falls
    /// back to [`num_inputs`](Self::num_inputs) when no per-bus layout was
    /// recorded (single-bus legacy).
    pub fn total_input_channels(&self) -> usize {
        if self.input_bus_channels.is_empty() {
            self.num_inputs
        } else {
            self.input_bus_channels.iter().sum()
        }
    }

    /// Total output channels across all audio output buses (main + aux). Falls
    /// back to [`num_outputs`](Self::num_outputs) when no per-bus layout was
    /// recorded (single-bus legacy).
    pub fn total_output_channels(&self) -> usize {
        if self.output_bus_channels.is_empty() {
            self.num_outputs
        } else {
            self.output_bus_channels.iter().sum()
        }
    }

    /// Sets whether the plugin has a MIDI **input** bus. The output direction is
    /// separate — see [`midi_output`](Self::midi_output).
    #[must_use]
    pub fn midi(mut self, has_midi: bool) -> Self {
        self.has_midi_input = has_midi;
        self
    }

    /// Sets whether the plugin emits MIDI the host can read back.
    #[must_use]
    pub fn midi_output(mut self, has_midi_output: bool) -> Self {
        self.has_midi_output = has_midi_output;
        self
    }

    /// Sets whether the plugin advertises `kSample64` processing.
    #[must_use]
    pub fn f64_support(mut self, supports: bool) -> Self {
        self.supports_f64 = supports;
        self
    }
}

/// A sample type the VST3 host renders: it names the width the plugin is
/// activated with and binds a block's channel slices of that type to the
/// process buffers.
///
/// This is the host's own seam: the FFI crate's process path is not generic
/// over the sample type. It is sealed: `f32` and `f64` are the two widths the
/// SDK defines, and the constants below must agree with the buffers the FFI
/// crate binds for each, so an outside impl could only get one wrong.
///
/// ```compile_fail,E0277
/// use tutti_plugin_types::Sample;
/// use tutti_plugin_types::SampleFormat;
/// use tutti_vst3_ffi::{BoundBuses, BusBuffers, SampleWidth, Vst3Error};
/// use tutti_vst3_host::Vst3Sample;
///
/// #[derive(Clone, Copy, Default)]
/// struct Half(u16);
/// impl Sample for Half {}
///
/// // The trait is sealed: `Half` cannot implement it, whatever it defines.
/// impl Vst3Sample for Half {
///     const FORMAT: SampleFormat = SampleFormat::Float32;
///     const WIDTH: SampleWidth = SampleWidth::F32;
///     const VST3_SYMBOLIC_SIZE: i32 = 0;
///     fn bind_inputs<'a>(
///         _: &'a mut BusBuffers,
///         _: &'a [&'a [Self]],
///     ) -> Result<BoundBuses<'a>, Vst3Error> {
///         unimplemented!()
///     }
///     fn bind_outputs<'a, 'b: 'a>(
///         _: &'a mut BusBuffers,
///         _: &'a mut [&'b mut [Self]],
///     ) -> Result<BoundBuses<'a>, Vst3Error> {
///         unimplemented!()
///     }
/// }
/// ```
pub trait Vst3Sample: tutti_plugin_types::Sample + sealed::Sealed {
    /// The format of this sample type.
    const FORMAT: SampleFormat;
    /// The width of this sample type.
    const WIDTH: SampleWidth;
    /// The `symbolicSampleSize` the plugin is told: `kSample32` or `kSample64`.
    const VST3_SYMBOLIC_SIZE: i32;

    /// Binds the input channels of a block.
    #[doc(hidden)]
    fn bind_inputs<'a>(
        buses: &'a mut BusBuffers,
        channels: &'a [&'a [Self]],
    ) -> Result<BoundBuses<'a>, FfiError>;

    /// Binds the output channels of a block.
    #[doc(hidden)]
    fn bind_outputs<'a, 'b: 'a>(
        buses: &'a mut BusBuffers,
        channels: &'a mut [&'b mut [Self]],
    ) -> Result<BoundBuses<'a>, FfiError>;
}

mod sealed {
    /// Implemented for the two widths the SDK defines, here and nowhere else.
    pub trait Sealed {}
    impl Sealed for f32 {}
    impl Sealed for f64 {}
}

impl Vst3Sample for f32 {
    const FORMAT: SampleFormat = SampleFormat::Float32;
    const WIDTH: SampleWidth = SampleWidth::F32;
    const VST3_SYMBOLIC_SIZE: i32 = K_SAMPLE_32_INT;

    fn bind_inputs<'a>(
        buses: &'a mut BusBuffers,
        channels: &'a [&'a [f32]],
    ) -> Result<BoundBuses<'a>, FfiError> {
        buses.bind_inputs_f32(channels)
    }

    fn bind_outputs<'a, 'b: 'a>(
        buses: &'a mut BusBuffers,
        channels: &'a mut [&'b mut [f32]],
    ) -> Result<BoundBuses<'a>, FfiError> {
        buses.bind_outputs_f32(channels)
    }
}

impl Vst3Sample for f64 {
    const FORMAT: SampleFormat = SampleFormat::Float64;
    const WIDTH: SampleWidth = SampleWidth::F64;
    const VST3_SYMBOLIC_SIZE: i32 = K_SAMPLE_64_INT;

    fn bind_inputs<'a>(
        buses: &'a mut BusBuffers,
        channels: &'a [&'a [f64]],
    ) -> Result<BoundBuses<'a>, FfiError> {
        buses.bind_inputs_f64(channels)
    }

    fn bind_outputs<'a, 'b: 'a>(
        buses: &'a mut BusBuffers,
        channels: &'a mut [&'b mut [f64]],
    ) -> Result<BoundBuses<'a>, FfiError> {
        buses.bind_outputs_f64(channels)
    }
}

#[cfg(test)]
mod plugin_info_bus_tests {
    use super::PluginInfo;

    /// No per-bus layout recorded → totals fall back to the flat bus-0 counts
    /// (single-bus legacy behaviour).
    #[test]
    fn empty_bus_layout_falls_back_to_flat_counts() {
        let info = PluginInfo::new("vst3.x", "X").audio_io(2, 2);
        assert!(info.input_bus_channels.is_empty());
        assert!(info.output_bus_channels.is_empty());
        assert_eq!(info.total_input_channels(), 2);
        assert_eq!(info.total_output_channels(), 2);
    }

    /// Multi-bus layout → totals sum every bus; bus-0 entry mirrors the flat
    /// count.
    #[test]
    fn multi_bus_layout_sums_all_buses() {
        // stereo main + mono sidechain in; stereo main + stereo aux out.
        let info = PluginInfo::new("vst3.x", "X")
            .audio_io(2, 2)
            .bus_channels(vec![2, 1], vec![2, 2]);
        assert_eq!(info.input_bus_channels, vec![2, 1]);
        assert_eq!(info.output_bus_channels, vec![2, 2]);
        assert_eq!(info.total_input_channels(), 3);
        assert_eq!(info.total_output_channels(), 4);
        // Main bus mirrors the flat count.
        assert_eq!(info.input_bus_channels[0], info.num_inputs);
        assert_eq!(info.output_bus_channels[0], info.num_outputs);
    }
}

#[cfg(test)]
mod host_type_tests {
    use super::{KeyEvent, KeyModifiers, PrefetchSupport};
    use vst3::Steinberg::Vst::ePrefetchableSupport_ as P;

    /// Each SDK value maps to its own variant and anything else is carried.
    #[test]
    fn prefetch_support_maps_each_sdk_value() {
        assert_eq!(
            PrefetchSupport::from_raw(crate::helpers::sdk_enum_u32(P::kIsNeverPrefetchable)),
            PrefetchSupport::Never
        );
        assert_eq!(
            PrefetchSupport::from_raw(crate::helpers::sdk_enum_u32(P::kIsYetPrefetchable)),
            PrefetchSupport::Yes
        );
        assert_eq!(
            PrefetchSupport::from_raw(crate::helpers::sdk_enum_u32(P::kIsNotYetPrefetchable)),
            PrefetchSupport::NotYet
        );
        assert_eq!(PrefetchSupport::from_raw(77), PrefetchSupport::Unknown(77));
    }

    /// The modifier bits are the SDK's `KeyModifier` values and combine and
    /// test as a set.
    #[test]
    fn key_modifiers_are_the_sdk_bits() {
        assert_eq!(KeyModifiers::SHIFT.bits(), 1);
        assert_eq!(KeyModifiers::ALTERNATE.bits(), 2);
        assert_eq!(KeyModifiers::COMMAND.bits(), 4);
        assert_eq!(KeyModifiers::CONTROL.bits(), 8);

        let both = KeyModifiers::SHIFT | KeyModifiers::COMMAND;
        assert_eq!(both.bits(), 5);
        assert!(both.contains(KeyModifiers::SHIFT));
        assert!(!both.contains(KeyModifiers::CONTROL));
        assert_eq!(
            KeyModifiers::SHIFT | KeyModifiers::SHIFT,
            KeyModifiers::SHIFT
        );
    }

    /// A character key carries no virtual key, and a virtual key no character.
    #[test]
    fn key_constructors_fill_exactly_one_code() {
        let c = KeyEvent::character(97);
        assert_eq!((c.character, c.virtual_key), (97, 0));
        let v = KeyEvent::virtual_key(11);
        assert_eq!((v.character, v.virtual_key), (0, 11));
    }
}
